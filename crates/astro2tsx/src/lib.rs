use biome_html_parser::parse_html;
use biome_languages::HtmlFileSource;

pub use crate::sourcemap::{ExtractedKind, ExtractedTag, GeneratedRange, Mapping};

/// Options controlling TSX emission. Defaults reproduce the upstream
/// `convertToTSX` defaults.
#[derive(Clone, Debug, Default)]
pub struct ConvertOptions {
    /// Display name used to derive the default-exported component
    /// identifier. Mirrors the upstream `filename` option.
    pub filename: Option<String>,
}

/// Result of a conversion. The `code` field is always populated; the rest
/// captures the metadata the upstream printer surfaces alongside the TSX.
#[derive(Debug, Default)]
pub struct ConvertResult {
    /// The emitted TSX code.
    pub code: String,
    /// Source-position mappings, as `(generated_offset, original_offset)`
    /// pairs. Consumers that need a JSON sourcemap can VLQ-encode this.
    pub mappings: Vec<Mapping>,
    /// Generated byte range covering the printed frontmatter section.
    pub frontmatter: GeneratedRange,
    /// Generated byte range covering the printed body section
    /// (`<Fragment>...</Fragment>`).
    pub body: GeneratedRange,
    /// Extracted `<script>` blocks plus event-handler attributes.
    pub scripts: Vec<ExtractedTag>,
    /// Extracted `<style>` blocks plus inline `style="..."` attributes.
    pub styles: Vec<ExtractedTag>,
    /// `true` when the parser surfaced one or more error diagnostics. The
    /// conversion still runs to completion regardless.
    pub has_parse_errors: bool,
}

/// Converts an Astro source file to TSX.
pub fn convert_to_tsx(source: &str, options: ConvertOptions) -> ConvertResult {
    let parse = parse_html(source, (&HtmlFileSource::astro()).into());
    let has_parse_errors = parse.has_errors();
    let root = parse.tree();

    let mut printer = printer::Printer::new(source);
    render::render_root(&mut printer, root, &options);

    ConvertResult {
        code: printer.output,
        mappings: printer.mappings,
        frontmatter: printer.frontmatter_range,
        body: printer.body_range,
        scripts: printer.scripts,
        styles: printer.styles,
        has_parse_errors,
    }
}
