//! Converts `.astro` source into TSX, mirroring the upstream Astro
//! compiler's `internal/printer/print-to-tsx.go`.
//!
//! The conversion is error-tolerant: it parses with Biome's HTML parser in
//! `Astro` mode and walks the resulting CST to emit TSX. Even malformed
//! input produces a best-effort TSX output, since the underlying parser
//! produces bogus nodes rather than failing outright.
//!
//! ```ignore
//! use astro2tsx::{convert_to_tsx, ConvertOptions};
//!
//! let result = convert_to_tsx(
//!     "---\nlet x = 1;\n---\n<h1>{x}</h1>",
//!     ConvertOptions::default(),
//! );
//! assert!(result.code.starts_with("/* @jsxImportSource astro */"));
//! ```

