use biome_html_parser::parse_html;
use biome_languages::HtmlFileSource;

pub use crate::types::{
    Diagnostic, DiagnosticSeverity, ExtractedKind, ExtractedScriptType, ExtractedTag,
    FrontmatterInfo, FrontmatterStatus, GeneratedRange, Mapping, SourceRange,
};

#[derive(Clone, Debug, Default)]
pub struct ConvertOptions {
    /// Filename used to derive the default-exported component name.
    pub filename: Option<String>,
    /// Appends declarations for `Fragment` and `Astro`.
    /// Props-aware `Astro` declarations are emitted independently of this option.
    pub ambient_types: bool,
}

/// `code` is always populated, whether or not the input parsed cleanly.
#[derive(Debug, Default)]
pub struct ConvertResult {
    pub code: String,
    pub(crate) component_name_range: GeneratedRange,
    /// Generated byte range of the clean-name re-export, including its trailing newline.
    /// Absent for dynamic routes, filenames without a matching clean component name,
    /// and names already exported by frontmatter.
    pub generated_component_export: Option<GeneratedRange>,
    /// Run starts, ascending: each mapping holds until the next one, with
    /// generated and original offsets advancing in lockstep.
    pub mappings: Vec<Mapping>,
    /// Generated byte range covering the printed frontmatter section.
    pub frontmatter_range: GeneratedRange,
    /// Generated byte range covering the template body section
    pub body: GeneratedRange,
    /// Extracted `<script>` blocks plus event-handler attributes.
    pub scripts: Vec<ExtractedTag>,
    /// Extracted `<style>` blocks plus inline `style="..."` attributes.
    pub styles: Vec<ExtractedTag>,
    pub has_parse_errors: bool,
    /// Parse diagnostics from the document and its expression bodies.
    pub diagnostics: Vec<Diagnostic>,
    pub frontmatter: FrontmatterInfo,
}

pub fn convert_to_tsx(source: &str, options: ConvertOptions) -> ConvertResult {
    let parse = parse_html(source, (&HtmlFileSource::astro()).into());
    let root = parse.tree();

    let mut printer = printer::Printer::new(source);
    let (component_name_range, generated_component_export) =
        render::render_root(&mut printer, root, &options);

    let mut diagnostics: Vec<Diagnostic> = parse
        .diagnostics()
        .iter()
        .map(|diagnostic| {
            let source = match biome_diagnostics::Diagnostic::location(diagnostic).span {
                Some(span) => SourceRange::new(u32::from(span.start()), u32::from(span.end())),
                None => SourceRange::new(0, source.len() as u32),
            };
            Diagnostic {
                message: diagnostic.message.to_string(),
                severity: DiagnosticSeverity::Error,
                source,
            }
        })
        .collect();
    let html_has_errors = !diagnostics.is_empty();
    diagnostics.extend(printer.diagnostics);
    for diagnostic in &mut diagnostics {
        let end = (diagnostic.source.end as usize).min(source.len());
        let start = (diagnostic.source.start as usize).min(end);
        diagnostic.source = SourceRange::new(
            source.floor_char_boundary(start) as u32,
            source.floor_char_boundary(end) as u32,
        );
    }
    diagnostics.sort_by_key(|diagnostic| (diagnostic.source.start, diagnostic.source.end));
    diagnostics.dedup();

    ConvertResult {
        code: printer.output,
        component_name_range,
        generated_component_export,
        mappings: printer.mappings,
        frontmatter_range: printer.frontmatter_range,
        body: printer.body_range,
        scripts: printer.scripts,
        styles: printer.styles,
        has_parse_errors: html_has_errors || printer.has_embedded_parse_errors,
        diagnostics,
        frontmatter: printer.frontmatter_info,
    }
}

#[cfg(test)]
mod tests {
    use crate::test_utils::assert_mapped_runs_are_verbatim;
    use crate::{ConvertOptions, convert_to_tsx};

    const PREFIX: &str = "/* @jsxImportSource astro */\n\n";

    #[test]
    fn generated_export_ranges_point_to_component_exports() {
        let source = "---\nconst marker = 'MyPageAstroComponent 𝒳';\ninterface Props<T> { value: T }\n---\n<p>{marker}</p>";
        for (filename, component, alias) in [
            ("MyPage.astro", "MyPageAstroComponent", Some("MyPage")),
            ("[slug].astro", "_Slug_AstroComponent", None),
            ("404.astro", "FourOhFourAstroComponent", None),
            ("[...path].astro", "AstroComponent", None),
            ("Ünicorn.astro", "ÜnicornAstroComponent", None),
        ] {
            let result = convert_to_tsx(
                source,
                ConvertOptions {
                    filename: Some(filename.to_string()),
                    ambient_types: true,
                },
            );
            assert!(!result.has_parse_errors, "{:?}", result.diagnostics);
            let range = result.component_name_range;
            assert_eq!(
                &result.code[range.start as usize..range.end as usize],
                component
            );
            assert!(result.code.contains("'MyPageAstroComponent 𝒳'"));
            assert!(
                result
                    .code
                    .contains(&format!("Parameters<typeof {component}>[0]"))
            );
            if let Some(alias) = alias {
                let range = result.generated_component_export.unwrap();
                assert_eq!(
                    &result.code[range.start as usize..range.end as usize],
                    format!("export {{ {component} as {alias} }};\n"),
                );
                assert_eq!(range.end as usize, result.code.len());
                assert!(range.start >= result.body.end);
                assert!(range.start >= result.frontmatter_range.end);
            } else {
                assert!(result.generated_component_export.is_none());
                assert!(!result.code.contains("export {"));
            }
            assert_mapped_runs_are_verbatim(source, &result, filename);
        }
    }

    #[test]
    fn named_component_exports_do_not_replace_explicit_exports() {
        for declaration in [
            "export const MyPage = 1;",
            "export function MyPage() {}",
            "export class MyPage {}",
            "export enum MyPage { Value }",
            "export namespace MyPage { export const value = 1; }",
            "export declare const MyPage: number;",
            "export declare function MyPage(): void;",
            "export interface MyPage { value: string }",
            "export type MyPage = string;",
            "export const { nested: [MyPage] } = data;",
            "const MyPage = 1; export { MyPage };",
            "const value = 1; export { value as MyPage };",
            "export { value as MyPage } from './other';",
            "export { MyPage } from './other';",
            "export * as MyPage from './other';",
            "export const MyP\\u0061ge = 1;",
            "const value = 1; export { value as 'MyPage' };",
        ] {
            let source = format!("---\n{declaration}\n---");
            let result = convert_to_tsx(
                &source,
                ConvertOptions {
                    filename: Some("MyPage.astro".to_string()),
                    ..Default::default()
                },
            );
            assert!(
                !result.has_parse_errors,
                "{source}: {:?}",
                result.diagnostics
            );
            assert!(
                result.generated_component_export.is_none(),
                "{}",
                result.code
            );
            assert!(
                result
                    .code
                    .contains("export default function MyPageAstroComponent(")
            );
            assert!(result.code.contains(declaration), "{}", result.code);
            assert_mapped_runs_are_verbatim(&source, &result, declaration);
        }
        for declaration in [
            "const MyPage = 1;",
            "export const value = () => { const MyPage = 1; return MyPage; };",
            "export const { value = (() => { const MyPage = 1; return MyPage; })() } = data;",
            "export const { MyPage: value } = data;",
            "const MyPage = 1; export { MyPage as other };",
            "export { MyPage as other } from './other';",
            "export * from './other';",
        ] {
            let source = format!("---\n{declaration}\n---");
            let result = convert_to_tsx(
                &source,
                ConvertOptions {
                    filename: Some("MyPage.astro".to_string()),
                    ..Default::default()
                },
            );
            assert!(
                !result.has_parse_errors,
                "{source}: {:?}",
                result.diagnostics
            );
            assert!(
                result.generated_component_export.is_some(),
                "{}",
                result.code
            );
            assert_mapped_runs_are_verbatim(&source, &result, declaration);
        }
    }

    #[test]
    fn diagnostics_stay_within_source_for_every_truncation() {
        for source in [
            "   ---\n`t a=1",
            "---\nconst é = `𝒳${a}`;\n---\n<p>{a}</p>",
            "<C v-for={items.map(x => ({x}))} @x=`${foo}` />",
            "{<div><!-- comment --><C x={a} /></div>}",
        ] {
            for end in (0..=source.len()).filter(|end| source.is_char_boundary(*end)) {
                let source = &source[..end];
                let result = convert_to_tsx(source, ConvertOptions::default());
                for diagnostic in &result.diagnostics {
                    let range = diagnostic.source;
                    assert!(
                        range.start <= range.end && range.end as usize <= source.len(),
                        "{source:?}: {diagnostic:?}"
                    );
                    assert!(source.is_char_boundary(range.start as usize));
                    assert!(source.is_char_boundary(range.end as usize));
                }
                assert_mapped_runs_are_verbatim(source, &result, source);
            }
        }
    }

    #[test]
    fn parser_errors_surface_but_do_not_block_emission() {
        let result = convert_to_tsx(
            "---\nconst items = [1];\n---\n{items.map(i => <div>{i}</div>)",
            ConvertOptions::default(),
        );
        assert!(result.has_parse_errors);
        assert!(result.code.starts_with(PREFIX));
    }

    #[test]
    fn diagnostics_carry_positions_pointing_at_the_problem() {
        let source = "<div>{x ==}</div>";
        let result = convert_to_tsx(source, ConvertOptions::default());
        assert!(!result.diagnostics.is_empty());
        for diagnostic in &result.diagnostics {
            assert!(!diagnostic.message.is_empty());
            assert!(
                diagnostic.source.end as usize <= source.len(),
                "{diagnostic:?} runs past the source"
            );
            assert!(diagnostic.source.start <= diagnostic.source.end);
        }
    }

    #[test]
    fn malformed_comments_and_fragments_report_the_offending_line() {
        for (line, problem) in [
            ("      {/*", "/*"),
            ("    < data-test=\"hello\"><div></div></>", "</>"),
        ] {
            let source = format!(
                "<html>\n  <head>\n    <title>Hello world</title>\n  </head>\n  <body>\n{line}\n  </body>\n</html>"
            );
            let result = convert_to_tsx(&source, ConvertOptions::default());
            assert!(result.has_parse_errors);
            assert!(result.code.contains(line));
            let start = source.find(problem).unwrap() as u32;
            assert!(
                result.diagnostics.iter().any(|diagnostic| {
                    diagnostic.source.start <= start
                        && diagnostic.source.end > start
                        && !diagnostic.message.is_empty()
                }),
                "{:?}",
                result.diagnostics
            );
            assert_mapped_runs_are_verbatim(&source, &result, line);
        }
    }

    #[test]
    fn tolerates_line_separators() {
        for input in [
            " ",
            "something something",
            "something  ",
            "   ",
            "\u{2028}",
            "something\u{2029}something",
            "something\u{2028}\u{2029}",
            "\u{2028}\u{2029}\u{2028}",
        ] {
            let actual = convert_to_tsx(input, ConvertOptions::default()).code;
            assert!(
                actual.starts_with(PREFIX),
                "input {input:?} produced no usable output"
            );
        }
    }

    #[test]
    fn malformed_input_never_panics_in_the_parser() {
        for input in ["<div></{<//", "<a></", "</", "<//", "<div></{", "{<//}"] {
            let result = convert_to_tsx(input, ConvertOptions::default());
            assert!(result.code.starts_with(PREFIX), "no output for {input:?}");
        }
    }

    #[test]
    fn unclosed_elements_are_emitted_as_written_and_flagged() {
        for (input, expected) in [
            ("<div>hello", "<div>hello"),
            ("<Card>\n  <p>text</p>", "<Card>\n  <p>text</p>"),
            ("<p>one<p>two", "<p>one<p>two"),
            ("<>{1}<p>x</p>", "<>{1}<p>x</p>"),
            (
                "<table><tr><td>a<td>b</tr></table>",
                "<td>a<td>b</tr></table>",
            ),
            ("<div>x</div", "<div>x</div"),
            ("<>x", "<>x"),
            ("<img /", "<img /"),
            ("<components.", "<components."),
            ("<myMarkdown.\n", "<myMarkdown.\n"),
            ("<div></div>\n<div", "<div></div>\n<div"),
            ("<div>\n<div\n</div>\n", "<div>\n<div\n</div>\n"),
            ("<div class={", "<div class={"),
            ("<div class=`></div>\n  ", "<div class=`></div>\n  "),
            ("<main id=\"gotcha />", "<main id=\"gotcha />"),
            ("<main id='gotcha/>", "<main id='gotcha/>"),
            (
                "<div>{[].map((something) => <div><Blocknote</div><div><Image</div>)}</div>",
                "<div>{[].map((something) => <div><Blocknote</div><div><Image</div>)}</div>",
            ),
        ] {
            let result = convert_to_tsx(input, ConvertOptions::default());
            assert!(
                result.code.contains(expected),
                "content lost for {input:?}:\n{}",
                result.code
            );
            assert!(
                !result.code.contains("</div>") || input.contains("</div>"),
                "a closing tag was synthesized for {input:?}:\n{}",
                result.code
            );
            assert!(result.has_parse_errors, "{input:?} must stay flagged");
            assert_mapped_runs_are_verbatim(input, &result, "unclosed as written");
        }

        let truncated = convert_to_tsx("<div>x</div", ConvertOptions::default());
        assert!(!truncated.code.contains("</div>"), "{}", truncated.code);
        let fragment = convert_to_tsx("<>x", ConvertOptions::default());
        assert!(!fragment.code.contains("</>"), "{}", fragment.code);
    }
}
